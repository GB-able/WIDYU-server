package com.widyu.fcm.application;

import static org.assertj.core.api.Assertions.assertThat;

import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

class GuardianSwitchSplitMigrationTest {

    private static final String SCRIPT =
            "src/main/resources/db/migration/V4__split_guardian_general_notification_setting.sql";

    @Test
    @DisplayName("일반을 끈 보호자를 이행하면 새 일반 스위치 11개가 꺼지고 일반 행은 사라지며 두 번 실행해도 같다")
    void 일반을_끈_보호자를_이행하면_새_일반_스위치가_꺼지고_다시_실행해도_같다() throws Exception {
        // given
        Path script = Path.of(SCRIPT);
        if (!Files.exists(script)) {
            script = Path.of("backend/widyu-api").resolve(SCRIPT);
        }
        String sql = Files.readString(script).replaceAll("(?m)^--.*$", "");
        try (Connection connection = DriverManager.getConnection(
                "jdbc:h2:mem:guardian_switch_split;MODE=MySQL;DB_CLOSE_DELAY=-1");
             Statement statement = connection.createStatement()) {
            statement.execute("CREATE TABLE `member` (`id` BIGINT PRIMARY KEY, `type` VARCHAR(16) NOT NULL)");
            statement.execute("CREATE TABLE `member_notification_setting` (`id` BIGINT GENERATED BY DEFAULT AS IDENTITY "
                    + "PRIMARY KEY, `member_id` BIGINT NOT NULL, `category` VARCHAR(32) NOT NULL, "
                    + "`enabled` TINYINT NOT NULL, UNIQUE(`member_id`, `category`))");
            statement.execute("INSERT INTO `member` VALUES (1, 'GUARDIAN'), (2, 'GUARDIAN'), (3, 'GUARDIAN'), (4, 'SENIOR')");
            // 1: 일반 OFF, 좋아요는 이미 켠 행이 있다. 2: 일반 ON. 3: 일반 없음, 복약 OFF. 4: 시니어 일반 OFF.
            statement.execute("INSERT INTO `member_notification_setting` (`member_id`, `category`, `enabled`) VALUES "
                    + "(1, 'GENERAL', 0), (1, 'ALBUM_LIKE', 1), (1, 'SAFE_ZONE', 0), "
                    + "(2, 'GENERAL', 1), (3, 'MEDICATION_CHECK', 0), (4, 'GENERAL', 0)");

            // when
            runTwice(statement, sql);

            // then
            List<String> rows = new ArrayList<>();
            try (ResultSet result = statement.executeQuery("SELECT `member_id`, `category`, `enabled` "
                    + "FROM `member_notification_setting` ORDER BY `member_id`, `category`")) {
                while (result.next()) {
                    rows.add(result.getLong(1) + ":" + result.getString(2) + ":" + result.getInt(3));
                }
            }
            assertThat(rows).containsExactly(
                    "1:ALBUM_COMMENT:0", "1:ALBUM_LIKE:1", "1:ALBUM_NEW_POST:0", "1:ALBUM_SENIOR_VIEWED:0",
                    "1:ALBUM_UPLOAD_COMPLETE:0", "1:CHEER_MESSAGE:0", "1:GOAL_ACHIEVED:0", "1:HEALTH_SCHEDULE:0",
                    "1:LEADER_CHANGED:0", "1:SAFE_ZONE:0", "1:SENIOR_OK_NOTICE:0", "1:SERVICE_NOTICE:0",
                    "3:MEDICATION_CHECK:0");
        }
    }

    private void runTwice(Statement statement, String sql) throws Exception {
        for (int run = 0; run < 2; run++) {
            for (String command : sql.split(";")) {
                if (!command.isBlank()) {
                    statement.execute(command.trim());
                }
            }
        }
    }
}
